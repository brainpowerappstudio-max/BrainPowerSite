import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { apps } from './deletion-config.mjs';

const developer = 'Brainpower Studio';
const email = 'brainpower.appstudio@gmail.com';
const site = 'https://brainpower-studio.vercel.app';
const root = new URL('../', import.meta.url);

const escapeHtml = (value) => value
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;');

const appPath = (app) => `/account-deletion/${app.slug}.html`;
const mailto = (subject, lines) => escapeHtml(
  `mailto:${email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(lines.join('\r\n'))}`,
);

