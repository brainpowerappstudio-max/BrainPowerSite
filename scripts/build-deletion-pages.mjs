function renderApp(app) {
  const name = app.displayName;
  const htmlName = escapeHtml(name);
  const title = `Account & Data Deletion – ${name}`;
  const intro = `This page explains how users of ${name}, developed by ${developer}, can request deletion of their account and associated personal data.`;
  const identifier = 'Email address or account ID associated with the app (if applicable):';
  const accountLink = mailto(`Account Deletion Request – ${name}`, [
    `Please delete my account and all associated user data for ${name} (Android package ${app.packageId}).`,
    '',
    identifier,
  ]);
  const dataLink = mailto(`Data Deletion Request – ${name}`, [
    `I would like to request deletion of specific personal data for ${name} (Android package ${app.packageId}) while keeping my account.`,
    '',
    identifier,
    'Data I would like deleted:',
  ]);
  const dataOnly = app.supportsDataOnlyDeletion === false
    ? `<p class="privacy-text">For deletion options available for this app, contact <a href="mailto:${email}">${email}</a>.</p>`
    : `<p class="privacy-text">Email us with the specific personal data you want deleted while keeping your account.${app.supportsDataOnlyDeletion === null ? ' Support will confirm whether it can fulfill your request.' : ''}</p>
          <a class="btn btn-ghost" href="${dataLink}">Request Data Deletion</a>`;
  const deletedData = app.deletedData?.length
    ? `
          <ul class="privacy-list">
${app.deletedData.map((category) => `            <li>${escapeHtml(category)}</li>`).join('\n')}
          </ul>`
    : '';
  const retainedData = app.retainedData.length
    ? `<ul class="privacy-list">
${app.retainedData.map(({ category, purpose, period }) => `            <li><strong>${escapeHtml(category)}</strong> is kept for ${escapeHtml(period)} for ${escapeHtml(purpose)}.</li>`).join('\n')}
          </ul>`
    : `<p class="privacy-text">Routine retention ends when the account is deleted. If a legal obligation requires retention, we keep only the affected records for the required period.</p>`;

  return layout(appPath(app), title, intro, `      <div class="privacy-header">
        <p class="privacy-eyebrow">Android app support</p>
        <h1 class="privacy-title">Account &amp; Data Deletion <span>– ${htmlName}</span></h1>
        <ul class="deletion-meta">
          <li><strong>Developer:</strong> ${developer}</li>
          <li><strong>Package ID:</strong> ${app.packageId}</li>
        </ul>
        <p class="privacy-intro">${escapeHtml(intro)}</p>
      </div>

      <div class="deletion-grid">
        <section class="privacy-section-block deletion-request">
          <h2 class="privacy-section-title">How to Request Account Deletion</h2>
          <div class="deletion-action">
            <a class="btn btn-primary" href="${accountLink}">Request Account Deletion</a>
            <p class="deletion-note">You can make a request without signing in to or installing the app. Please leave passwords and payment details out of your email.</p>
          </div>
          <ol class="privacy-list">
            <li>Select <strong>Request Account Deletion</strong> to open an email draft.</li>
            <li>Send the email to <a href="${accountLink}">${email}</a>. If the button doesn’t open an email draft, you can write to that address directly.</li>
            <li>Include the email address or account ID linked to this app, if applicable.</li>
            <li>Ask us to delete your account and its associated data.</li>
            <li>Our support team will verify and process your request.</li>
          </ol>
        </section>

        <section class="privacy-section-block">
          <h2 class="privacy-section-title">Request Data Deletion</h2>
          ${dataOnly}
        </section>

        <section class="privacy-section-block">
          <h2 class="privacy-section-title">What Data Will Be Deleted</h2>
          <p class="privacy-text">Once we verify an account deletion request, we delete the account and all associated user data, subject to any legally required retention.</p>${deletedData}
        </section>

        <section class="privacy-section-block">
          <h2 class="privacy-section-title">Data Retention</h2>
          ${retainedData}
        </section>

        <section class="privacy-section-block">
          <h2 class="privacy-section-title">Processing Time</h2>
          <p class="privacy-text">${escapeHtml(app.processingTime)}</p>
        </section>

        <section class="privacy-section-block deletion-help">
          <h2 class="privacy-section-title">Need Help?</h2>
          <p class="privacy-text"><strong>Support Email:</strong> <a href="mailto:${email}">${email}</a></p>
          <p class="privacy-text"><strong>Developer:</strong> ${developer}</p>
          <p class="privacy-text"><a href="/privacy-policy.html">Privacy Policy</a></p>
        </section>
      </div>`);
}

function renderDirectory() {
  const title = 'Account & Data Deletion';
  const intro = 'Select your app to find out how to request account and data deletion from Brainpower Studio.';
  const otherAppLink = mailto('Account and Data Deletion Request', [
    'App name:',
    'Email address or account ID associated with the app (if applicable):',
    'Account or data you want deleted:',
  ]);

  return layout('/account-deletion.html', title, intro, `      <div class="privacy-header">
        <p class="privacy-eyebrow">Android app support</p>
        <h1 class="privacy-title">Account &amp; Data Deletion</h1>
        <p class="privacy-intro">${intro}</p>
      </div>

      <section class="privacy-section-block deletion-directory">
        <h2 class="privacy-section-title">Find Your App</h2>
        <ul class="privacy-list">
${apps.map((app) => `          <li><a href="${appPath(app)}">${escapeHtml(app.displayName)}</a></li>`).join('\n')}
        </ul>
        <p class="privacy-text">For other apps, email <a href="${otherAppLink}">${email}</a> with the app name, your account email or ID if applicable, and what you want deleted.</p>
      </section>`);
}

const pages = new Map([
  ...apps.map((app) => [appPath(app), renderApp(app)]),
  ['/account-deletion.html', renderDirectory()],
]);

const check = process.argv.includes('--check');
if (!check) {
  await mkdir(new URL('account-deletion/', root), { recursive: true });
}

for (const [path, html] of pages) {
  const file = new URL(path.slice(1), root);
  if (check) {
    const current = await readFile(file, 'utf8').catch((error) => {
      if (error.code === 'ENOENT') return '';
      throw error;
    });
    if (current.replaceAll('\r\n', '\n') !== html) {
      console.error(`${path} is out of date. Run node scripts/build-deletion-pages.mjs.`);
      process.exitCode = 1;
    }
  } else {
    await writeFile(file, html);
  }
}
